import fs from 'node:fs';
import assert from 'node:assert/strict';
const save=fs.readFileSync(new URL('../admin-product-save-v2.js',import.meta.url),'utf8');
const api=fs.readFileSync(new URL('../functions/api/upload-image.js',import.meta.url),'utf8');
assert.match(save,/new FormData/,'Use same-origin multipart upload');
assert.match(save,/form\.append\('image'/,'Send original selected file as multipart');
assert.match(save,/\/api\/upload-image/,'Use PILAR same-origin upload endpoint');
assert.doesNotMatch(save,/PilarImagePro\?\.optimizeFile/,'Phone must not decode or normalize images before upload');
assert.doesNotMatch(save,/S\.storage\.from\('product-images'\)\.upload\(/,'Do not upload cross-origin from Android');
assert.match(save,/withTimeout\(fetch\(/,'Upload must have a client timeout');
assert.match(api,/ftyp/,'Server must inspect HEIC\/HEIF file signatures');
assert.match(api,/libheif-js/,'Server owns HEIC\/HEIF decoding');
assert.match(api,/jpeg-js/,'Server normalizes decoded HEIC\/HEIF to JPEG');
assert.match(api,/AbortSignal\.timeout/,'Server-side storage upload must have a timeout');
assert.match(save,/failedImages\s*>\s*0/,'Failed upload keeps editor open');
console.log('PASS server image pipeline regression');
